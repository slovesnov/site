function switchGame() {
	let b = gAlgorithmIndex > 1
	gDigits = b ? 6 : 10
	gArray = [...new Permutations(4, gDigits, b ? Permutations.PERMUTATIONS_WITH_REPLACEMENTS : Permutations.PERMUTATIONS_WITHOUT_REPLACEMENTS)].map(e => +e.join(''))
	loadTree()
}

