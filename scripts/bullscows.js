function makeArray(n, random) {
	let i, j, t, a = Array.from({ length: n }, (_, i) => i)
	if (random) {
		for (i = 0; i < n - 1; i++) {
			j = getRandom(n - i);
			if (j == 0) {
				continue;
			}
			j += i;
			[a[i], a[j]] = [a[j], a[i]]
		}
	}
	return a
}

//apply gRandomDigits,gRandomPositions to turn
function applyRandom(n) {
	let i, r = []
	for (i = 0; i < 4; i++) {
		r[gRandomPositions[i]] = gRandomDigits[n.charCodeAt(i) - ZERO_CODE]
	}
	return r.join('')
}

//return random [0..max)
function getRandom(max) {
	return Math.floor(Math.random() * max);
}

