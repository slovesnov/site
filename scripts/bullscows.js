//solve all tree and get tree statistics
function getStatistics() {
	let i, j, k, l, layer, pt, r, r0
	//r0 statistics
	let stat = new Array(BC40 + 1)
	for (i = 0; i < stat.length; i++) {
		stat[i] = new Array(8)
		for (j = 0; j < 8; j++) {
			stat[i][j] = 0
		}
	}

	let layerTotal = new Array(8)//total amount of layers
	let maxLayer = 0;
	for (i = 0; i < 8; i++) {
		layerTotal[i] = 0;
	}

	for (i = 0; i < gArray.length; i++) {
		r = getResponse(gArray[i], gArray[0])
		for (pt = 0, layer = 1; ; layer++) {
			r = getResponse(gArray[i], gTree[pt].turn)
			if (layer == 1) {
				r0 = r
			}

			if (r == BC40) {
				stat[r0][layer]++
				layerTotal[layer]++
				if (layer > maxLayer) {
					maxLayer = layer
				}
				break;
			}
			pt = gTree[pt].child[r];

			if (layer > 8) {
				alert("error186 " + gArray[i]);
				return;
			}
		}//for(pt)
	}//for(i)

	//response statistics
	j = '<table width="100%" class="single" id="ts' + oName[gAlgorithmIndex] + '">'
		+ '<tr><th align="center" colspan=' + (ENUM_RESPONSE.length + 3) + '>' + languageString[4] + ' - ' + oName[gAlgorithmIndex] + '&nbsp;&nbsp;' + languageString[13] + ' - ' + gTree.length + '&nbsp;&nbsp;' + languageString[25] + ' - ' + formatNumber(gArray.length * 100 / gTree.length, 1) + '%'
		+ '<tr><td><td><th colspan=' + ENUM_RESPONSE.length + ' align="center">' + languageString[14] + '<th rowspan=2 align="center">' + languageString[15] + '<tr><td><td>'
	for (k = 0; k < ENUM_RESPONSE.length; k++) {
		i = ENUM_RESPONSE[k]
		j += '<th align="center">' + BULL(i) + '.' + COW(i)
	}
	j += '<tr><th rowspan=' + maxLayer + ' align="center">' + [...languageString[21]].join('<br>')

	for (r0 = 0, layer = 1; layer < 8; layer++) {
		if (layerTotal[layer] == 0) {
			break;
		}
		if (layer > 1) {
			j += '<tr>'
		}
		j += '<th align="center">' + layer
		for (k = 0; k < ENUM_RESPONSE.length; k++) {
			i = ENUM_RESPONSE[k]
			pt = stat[i][layer];
			j += '<td align="right">' + (pt == 0 ? '&nbsp;' : pt)//use nbsp to draw border for cell
		}
		j += '<td align="right"><b>' + layerTotal[layer] + '</b>'
	}

	//total numbers
	j += '<tr><th colspan=2 align="center">' + languageString[15] + '<br>' + languageString[16];
	for (r = k = 0; k < ENUM_RESPONSE.length; k++) {
		i = ENUM_RESPONSE[k]
		for (r0 = 0, layer = 1; layer < 8; layer++) {
			r0 += stat[i][layer];
		}
		j += '<th align="right">' + r0
		r += r0
	}
	j += '<td align="right">' + r //total items

	//total turns
	j += '<tr><th colspan=2 align="center">' + languageString[15] + '<br>' + languageString[17];
	for (pt = k = 0; k < ENUM_RESPONSE.length; k++) {
		i = ENUM_RESPONSE[k]
		for (l = 0, layer = 1; layer < 8; layer++) {
			l += stat[i][layer] * layer
		}
		j += '<th align="right">' + l
		pt += l
	}
	pt += ''
	if (pt > 9999) {
		pt = pt.substring(0, 2) + ' ' + pt.substring(2)
	}
	j += '<td align="right">' + pt

	//average
	j += '<tr><th colspan=2 align="center">' + languageString[18]
	for (pt = r = k = 0; k < ENUM_RESPONSE.length; k++) {
		i = ENUM_RESPONSE[k]
		for (l = r0 = 0, layer = 1; layer < 8; layer++) {
			r0 += stat[i][layer];
			l += stat[i][layer] * layer
		}
		j += '<th align="right">' + formatNumber(l / r0, 3)
		pt += l
		r += r0
	}
	return j + '<td align="right">' + formatNumber(pt / r, 3) //total avg
		+ '</table>'
}

