START = '#'.charCodeAt(0)
RADIX = 127 - START

function parseDigit(c) {
	return c - (c >= '\\'.charCodeAt(0)) - START
}

function parseNumber(b) {
	if (b.length == 0) {
		return 0;
	}
	else if (b.length == 1) {
		return parseDigit(b.charCodeAt(0));
	}
	else {
		return parseDigit(b.charCodeAt(0)) * (127 - START) + parseDigit(b.charCodeAt(1));
	}
}
