function getResponse(n1, n2) {
	let r = 0
	let i;
	let a = new Array(gDigits);
	let n = [];

	for (i = 0; i < 2; i++) {
		r = numberToString(i == 0 ? n1 : n2)
		if (r.length != 4) {
			return 'error70 ' + r
		}
		n[i] = new Array(4);
		for (j = 0; j < 4; j++) {
			n[i][j] = r.charCodeAt(j) - ZERO_CODE
		}
	}

	for (i = 0; i < gDigits; i++) {
		a[i] = 0;
	}

	for (r = i = 0; i < 4; i++) {
		if (n[0][i] == n[1][i]) {
			r += 5;
		}
		else {
			if (a[n[0][i]]++ < 0) {
				r++;
			}
			if (a[n[1][i]]-- > 0) {
				r++;
			}
		}
	}
	return r
}

