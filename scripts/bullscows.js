function loadTree() {
	let i, j, k, l, m, node, recent = new Array(ENUM_RESPONSE.length - 1), s = o[gAlgorithmIndex], q = new Array(MBC)
	gTree = [{ recent: gArray }]
	for (l = i = 0; i < gTree.length; i++) {
		node = gTree[i]
		if (node.recent.length == 1) {
			node.turn = node.recent[0]
			node.child = undefined
		}
		else {
			node.turn = -1
			if (node.recent.length == 2) {
				node.turn = node.recent[0]
			}
			else if (node.recent.length <= ENUM_RESPONSE.length) {
				for (j = 0; j < node.recent.length; j++) {
					for (k = 0; k < q.length; k++) {
						q[k] = false;
					}
					for (k = 0; k < node.recent.length; k++) {
						if (k == j) {
							continue;
						}
						m = getResponse(node.recent[j], node.recent[k]);
						if (q[m]) {
							break;
						}
						q[m] = true;
					}
					if (k == node.recent.length) {
						node.turn = node.recent[j]
						break;
					}
				}
			}
			if (node.turn == -1) {
				node.turn = gArray[parseNumber(s.substring(l, l + 2))]
				l += 2
			}

			node.child = new Array(MBC)/*size is MBC!*/

			//split recent
			for (j = 0; j < recent.length; j++) {
				recent[j] = []
			}
			for (j = 0; j < node.recent.length; j++) {
				k = getResponse(node.turn, node.recent[j])
				if (k != BC40) {
					recent[ENUM_RESPONSE.indexOf(k)].push(node.recent[j])
				}
			}

			for (j = 0; j < recent.length; j++) {
				if (recent[j].length == 0) {
					node.child[ENUM_RESPONSE[j]] = 0
				}
				else {
					node.child[ENUM_RESPONSE[j]] = gTree.length
					gTree.push({ recent: recent[j] })
				}
			}
		}
	}
}

