function writeHtmlNode(id, level, response, avg) {
	let node = gTree[id], i, child = node.child, s = '<li' + (id == 0 || child == undefined ? '' : ' class="closed"') + '><span>';
	if (id != 0) {
		s += BULL(response) + '.' + COW(response) + ' '
	}
	s += languageString[11] + '' + level + ' ' + numberToString(node.turn) + ' (' + (avg ? '' : (node.nth + languageString[24] + ' ')) + node.estimate + ') [' + node.nodes + ']</span>'
	gs += s

	if (child != undefined) {
		gs += '<ul>'
		for (i = 0; i < child.length; i++) {
			if (child[i] == undefined || child[i] == 0) {
				continue
			}
			writeHtmlNode(child[i], level + 1, i, avg)
		}
		gs += '</ul>'
	}
	gs += '</li>'
}

function estimateNode(id, level, avg) {
	let node = gTree[id]
	let i, j, child = node.child
	let recent = node.recent
	node.nodes = recent.length
	if (child == undefined) {
		if (avg) {
			node.estimate = level
		}
		else {
			node.nth = level
			node.estimate = 1
		}
		return
	}

	if (avg) {
		node.estimate = 0
	}
	else {
		node.nth = 0
	}
	for (i = 0; i < recent.length; i++) {
		j = getResponse(node.turn, recent[i])
		if (j == BC40) {
			if (avg) {
				node.estimate += level
			}
		}
	}
	for (i = 0; i < child.length; i++) {
		j = child[i]
		if (j == undefined || j == 0) {
			continue
		}
		estimateNode(j, level + 1, avg)
		if (avg) {
			node.estimate += gTree[j].estimate
		}
		else {
			if (gTree[j].nth > node.nth) {
				node.nth = gTree[j].nth;
				node.estimate = gTree[j].estimate
			}
			else if (gTree[j].nth == node.nth) {
				node.estimate += gTree[j].estimate
			}
		}
	}
}

